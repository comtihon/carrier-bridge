/**
 * Tier 2: a binding whose computation a language model wrote.
 *
 * The one idea this file exists to enforce in the UI: **tier is an outcome we
 * display, never a choice the user makes.** There is no "use generated code"
 * switch anywhere below. The user types the same instruction they would for
 * tier 1; if a declarative form cannot express it they are *shown why* and
 * offered an explicit [Generate code] button, and nothing is generated until
 * they press it. Escalation is never silent and never automatic, because tier 2
 * is code execution and that is the user's decision to make.
 *
 * The flow, and why each stop exists:
 *
 *   instruction -> tier-1 check     the form is tried first, always
 *   -> escalation panel             the reason, plus [Generate code] and the
 *                                   [Simplify instruction] way back out
 *   -> questions (maybe)            a model that does not know which column
 *                                   "date" means asks instead of guessing
 *   -> review                       the code, the model's one-line rationale,
 *                                   and its output ON THE USER'S OWN ROWS
 *   -> explicit confirm             compiling is not activating
 *
 * After that a binding can go stale — the header row changed, or the frozen
 * test stopped reproducing — and says so with a [Re-test] / [Recompile]. A
 * write additionally needs re-confirmation, because a stale write is the one
 * case that must never quietly re-author itself.
 */

// ─── Badges ──────────────────────────────────────────────────────────────────

function verifiedLabel(status: ComputeStatus): string {
  const days = status.golden?.verified_days_ago;
  if (days === null || days === undefined) return "never verified";
  if (days < 1) return "last verified today";
  return `last verified ${Math.round(days)}d ago`;
}

/**
 * The tier badge, in the list and in the editor.
 *
 * Tier 1 gets to say "no code", and that is the point of showing it at all: a
 * user scanning a list of bindings should be able to see which ones are plain
 * mappings without opening them.
 */
export function BindingTierBadge({
  status,
  className,
}: {
  status?: ComputeStatus;
  className?: string;
}) {
  if (!status || !status.generated) {
    return (
      <span
        className={clsx(
          "inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[9px] font-medium shrink-0",
          "bg-emerald-950/50 text-emerald-300 border border-emerald-900",
          className,
        )}
        title="A declarative mapping: every column was picked from the sheet's own header row, and the binding contains no code."
      >
        <CheckCircle2 className="w-2.5 h-2.5" />
        Mapped — deterministic · no code
      </span>
    );
  }

  const stale = Boolean(status.stale);
  const inert = !status.activated;
  return (
    <span className={clsx("inline-flex items-center gap-1 shrink-0", className)}>
      <span
        className={clsx(
          "inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[9px] font-medium border",
          stale
            ? "bg-red-950/50 text-red-300 border-red-900"
            : "bg-violet-950/50 text-violet-300 border-violet-900",
        )}
        title={
          `Generated by ${status.model_id ?? "a language model"} from: ` +
          `${status.instruction ?? "(no instruction recorded)"}`
        }
      >
        <Cog className="w-2.5 h-2.5" />
        Generated code — review required
      </span>
      <span
        className={clsx(
          "text-[9px]",
          stale ? "text-red-400" : inert ? "text-amber-400" : "text-slate-500",
        )}
      >
        {stale ? "stale" : inert ? "not activated" : verifiedLabel(status)}
      </span>
      {status.edited_by_human && (
        <span
          className="text-[9px] text-sky-400"
          title="A person edited this code, so it is no longer regenerated."
        >
          hand-edited
        </span>
      )}
    </span>
  );
}

// ─── The tier-1 check ────────────────────────────────────────────────────────

/**
 * Why a declarative form cannot express *instruction*, or null if it can.
 *
 * A deliberately conservative, local check whose only job is to decide which
 * panel to show next. It is not the authority on anything — the backend is,
 * and it answers by actually trying to compile — so a false negative here just
 * means the user is told to use the form, and a false positive means they are
 * offered a button they do not have to press.
 *
 * The categories are the ones a form genuinely cannot do: a form maps a column
 * to a value, so it can filter and project rows but cannot combine them.
 */
export function tier1Rejection(instruction: string): string | null {
  const text = instruction.toLowerCase();
  const has = (...words: string[]) => words.some((w) => text.includes(w));

  const aggregation = has(
    "sum", "total", "average", "avg", "mean", "median", "count", "how many",
    "maximum", "minimum", "largest", "smallest", "highest", "lowest",
  );
  const grouping = has("group", "per ", "by owner", "by month", "each ", "breakdown");
  const arithmetic = has(
    "percent", "%", "ratio", "difference", "subtract", "multiply", "divide",
    "days between", "elapsed", "running",
  );
  const across = has("across rows", "all rows", "combine", "roll up", "rollup");

  if (aggregation && grouping) return "grouping + aggregation across rows";
  if (aggregation) return "aggregation across rows";
  if (grouping) return "grouping rows into one value per group";
  if (arithmetic) return "arithmetic derived from more than one cell";
  if (across) return "combining several rows into one result";
  return null;
}

// ─── Panel ───────────────────────────────────────────────────────────────────

type Phase =
  | { kind: "idle" }
  | { kind: "escalate"; reason: string }
  | { kind: "asking"; needs: ComputeNeed[] }
  | { kind: "review"; result: CompileComputeResult }
  | { kind: "error"; message: string };

function summarise(output: unknown): string {
  try {
    const text = JSON.stringify(output, null, 2);
    return text.length > 4000 ? `${text.slice(0, 4000)}\n… (truncated)` : text;
  } catch {
    return String(output);
  }
}

export function SheetComputePanel({
  sourceId,
  binding,
  /** Tier-2 WRITE bindings are hidden entirely when the backend flag is off. */
  writesEnabled = false,
  onChanged,
}: {
  sourceId: string;
  binding: SheetBinding;
  writesEnabled?: boolean;
  onChanged?: () => void;
}) {
  const name = binding.name;
  const status = binding.compute_status;
  const generated = Boolean(status?.generated ?? binding.compute);

  const [instruction, setInstruction] = useState(status?.instruction ?? "");
  const [answers, setAnswers] = useState<Record<string, string>>(status?.answers ?? {});
  const [phase, setPhase] = useState<Phase>({ kind: "idle" });
  const [busy, setBusy] = useState<string | null>(null);
  const [code, setCode] = useState(binding.compute?.code ?? "");
  const [editingCode, setEditingCode] = useState(false);
  const [notice, setNotice] = useState<string | null>(null);

  // A tier-2 write is not offered at all while the backend flag is off: the
  // honest thing is for the capability to be absent, not present-and-failing.
  const writeBlocked = binding.operation === "write" && !writesEnabled;

  const fail = (err: unknown, fallback: string) =>
    setPhase({
      kind: "error",
      message: err instanceof Error ? err.message : fallback,
    });

  const compile = useCallback(
    async (payload: { instruction?: string; answers?: Record<string, string>; force?: boolean }) => {
      setBusy("compile");
      setNotice(null);
      try {
        const result = await compileSheetBindingCode(sourceId, name, payload);
        if (result.status === "needs") {
          setPhase({ kind: "asking", needs: result.needs ?? [] });
        } else {
          setCode(result.code ?? "");
          setEditingCode(false);
          setPhase({ kind: "review", result });
          onChanged?.();
        }
      } catch (err) {
        fail(err, "The compile failed");
      } finally {
        setBusy(null);
      }
    },
    [name, onChanged, sourceId],
  );

  const check = useCallback(() => {
    setNotice(null);
    const reason = tier1Rejection(instruction);
    if (!reason) {
      // The form can already do this, so say so rather than generating code
      // nobody needs. Tier 1 is always the better outcome.
      setNotice(
        "The form above can express this — fill in the mode, columns and filter " +
          "instead. A declarative binding is deterministic and needs no review, " +
          "so it is always preferable to generated code.",
      );
      setPhase({ kind: "idle" });
      return;
    }
    setPhase({ kind: "escalate", reason });
  }, [instruction]);

  const act = useCallback(
    async (
      label: string,
      fn: () => Promise<{ status: string; error?: string; compute?: ComputeStatus }>,
    ) => {
      setBusy(label);
      setNotice(null);
      try {
        const result = await fn();
        if (result.status === "stale") {
          setPhase({ kind: "error", message: result.error ?? "This binding is stale." });
        } else {
          setPhase({ kind: "idle" });
          setNotice(`${label} succeeded.`);
        }
        onChanged?.();
      } catch (err) {
        fail(err, `${label} failed`);
      } finally {
        setBusy(null);
      }
    },
    [onChanged],
  );

  if (writeBlocked && !generated) return null;

  return (
    <div className="space-y-2 rounded-lg border border-violet-900/60 bg-violet-950/10 p-3">
      <div className="flex items-center gap-2">
        <Sparkles className="w-3.5 h-3.5 text-violet-400" />
        <span className="text-xs font-medium text-violet-300">Computation</span>
        <span className="flex-1" />
        <BindingTierBadge status={status} />
      </div>

      {/* ── The instruction box. Identical for both tiers: the user describes
           what they want and the backend decides how it is satisfied. ── */}
      {!generated && (
        <>
          <p className="text-[10px] text-slate-500">
            Describe what this binding should compute. Simple reads and writes are
            handled by the form above — describe something here only if the form
            cannot express it.
          </p>
          <textarea
            aria-label="Instruction"
            value={instruction}
            onChange={(e) => setInstruction(e.target.value)}
            rows={2}
            placeholder="e.g. total hours by owner for open rows this quarter"
            className={clsx(dsFieldCls, "text-xs w-full")}
          />
          <button
            type="button"
            disabled={!instruction.trim() || busy !== null}
            onClick={check}
            className="flex items-center gap-1 px-2.5 py-1.5 rounded-md bg-slate-800 hover:bg-slate-700 border border-slate-700 text-[11px] text-sky-400 disabled:opacity-50"
          >
            Check what this needs
          </button>
        </>
      )}

      {notice && (
        <p className="text-[11px] text-sky-300 bg-sky-950/30 border border-sky-900 rounded-md px-2 py-1">
          {notice}
        </p>
      )}

      {/* ── Escalation. Explicit, with the reason and a way back out. ── */}
      {phase.kind === "escalate" && (
        <div className="space-y-2 rounded-md border border-amber-900 bg-amber-950/20 p-2.5">
          <div className="flex items-start gap-1.5">
            <AlertTriangle className="w-3.5 h-3.5 text-amber-400 shrink-0 mt-0.5" />
            <div className="space-y-1">
              <p className="text-[11px] text-amber-200">
                A declarative binding cannot express this: <strong>{phase.reason}</strong>.
              </p>
              <p className="text-[10px] text-slate-400">
                The alternative is to have a language model write the computation as
                a small Python function. It runs sandboxed and can only produce
                values for the columns this binding already names — but it is still
                code, and you will be asked to read it before it runs.
              </p>
            </div>
          </div>
          {writeBlocked ? (
            <p className="text-[10px] text-red-300 bg-red-950/30 border border-red-900 rounded px-2 py-1">
              Generated-code writes are disabled on this backend. Compose this as a
              generated <em>read</em> binding plus a separate step that writes the
              result with a declarative binding.
            </p>
          ) : (
            <div className="flex flex-wrap gap-1.5">
              <button
                type="button"
                disabled={busy !== null}
                onClick={() => compile({ instruction, answers })}
                className="flex items-center gap-1 px-2.5 py-1.5 rounded-md bg-violet-900/60 hover:bg-violet-900 border border-violet-700 text-[11px] text-violet-100 disabled:opacity-50"
              >
                {busy === "compile" ? (
                  <Loader2 className="w-3 h-3 animate-spin" />
                ) : (
                  <Code2 className="w-3 h-3" />
                )}
                Generate code
              </button>
              <button
                type="button"
                disabled={busy !== null}
                onClick={() => {
                  setPhase({ kind: "idle" });
                  setNotice(
                    "Try describing a simpler read — for example the rows themselves, " +
                      "filtered — and do the arithmetic in a later workflow step. A " +
                      "declarative binding needs no review and cannot drift.",
                  );
                }}
                className="px-2.5 py-1.5 rounded-md bg-slate-800 hover:bg-slate-700 border border-slate-700 text-[11px] text-slate-300 disabled:opacity-50"
              >
                Simplify instruction
              </button>
            </div>
          )}
        </div>
      )}

      {/* ── Ambiguity questions, as a small form of dropdowns. ── */}
      {phase.kind === "asking" && (
        <div className="space-y-2 rounded-md border border-sky-900 bg-sky-950/20 p-2.5">
          <p className="text-[11px] text-sky-200">
            Two things about the data are ambiguous. Answering them is what makes a
            later recompile reproduce this result rather than guess again.
          </p>
          {phase.needs.map((need) => (
            <div key={need.question} className="space-y-1">
              <label className="text-[10px] text-slate-400">{need.question}</label>
              {need.options.length > 0 ? (
                <select
                  aria-label={need.question}
                  value={answers[need.question] ?? ""}
                  onChange={(e) =>
                    setAnswers({ ...answers, [need.question]: e.target.value })
                  }
                  className={clsx(dsFieldCls, "text-xs w-full")}
                >
                  <option value="">Choose…</option>
                  {need.options.map((option) => (
                    <option key={option} value={option}>
                      {option}
                    </option>
                  ))}
                </select>
              ) : (
                <input
                  aria-label={need.question}
                  value={answers[need.question] ?? ""}
                  onChange={(e) =>
                    setAnswers({ ...answers, [need.question]: e.target.value })
                  }
                  className={clsx(dsFieldCls, "text-xs w-full")}
                />
              )}
            </div>
          ))}
          <button
            type="button"
            disabled={
              busy !== null ||
              phase.needs.some((n) => !(answers[n.question] ?? "").trim())
            }
            onClick={() => compile({ instruction, answers })}
            className="flex items-center gap-1 px-2.5 py-1.5 rounded-md bg-violet-900/60 hover:bg-violet-900 border border-violet-700 text-[11px] text-violet-100 disabled:opacity-50"
          >
            {busy === "compile" ? (
              <Loader2 className="w-3 h-3 animate-spin" />
            ) : (
              <Code2 className="w-3 h-3" />
            )}
            Generate with these answers
          </button>
        </div>
      )}

      {/* ── Review: the code, the rationale, the output on the user's rows. ── */}
      {phase.kind === "review" && (
        <div className="space-y-2 rounded-md border border-violet-800 bg-slate-900/60 p-2.5">
          <p className="text-[11px] text-violet-200">
            Compiled, and <strong>not running yet</strong>. It passed the static
            checks, ran twice in the sandbox with the same result, and produced the
            output below on your own sample rows.
          </p>
          {phase.result.rationale && (
            <p className="text-[10px] text-slate-400 italic">
              {phase.result.rationale}
            </p>
          )}

          <div className="space-y-1">
            <div className="flex items-center gap-2">
              <span className="text-[10px] text-slate-500">Generated code</span>
              <span className="flex-1" />
              <button
                type="button"
                onClick={() => setEditingCode((v) => !v)}
                className="flex items-center gap-1 px-1.5 py-0.5 rounded text-[10px] text-sky-400 hover:bg-slate-800"
              >
                <Pencil className="w-2.5 h-2.5" />
                {editingCode ? "Cancel edit" : "Edit"}
              </button>
            </div>
            {editingCode ? (
              <>
                <textarea
                  aria-label="Generated code"
                  value={code}
                  onChange={(e) => setCode(e.target.value)}
                  rows={14}
                  spellCheck={false}
                  className={clsx(dsFieldMonoCls, "w-full text-[10px]")}
                />
                <p className="text-[10px] text-amber-400">
                  Saving your edit stops this binding being regenerated, so a later
                  recompile can never overwrite your fix.
                </p>
                <button
                  type="button"
                  disabled={busy !== null}
                  onClick={() =>
                    act("Save edit", () => editSheetBindingCode(sourceId, name, code))
                  }
                  className="flex items-center gap-1 px-2.5 py-1.5 rounded-md bg-slate-800 hover:bg-slate-700 border border-slate-700 text-[11px] text-sky-400 disabled:opacity-50"
                >
                  {busy === "Save edit" ? (
                    <Loader2 className="w-3 h-3 animate-spin" />
                  ) : (
                    <Check className="w-3 h-3" />
                  )}
                  Save edit
                </button>
              </>
            ) : (
              <pre className="overflow-x-auto rounded-md border border-slate-700 bg-slate-950/70 p-2 text-[10px] font-mono text-slate-300">
                {code}
              </pre>
            )}
          </div>

          <div className="space-y-1">
            <span className="text-[10px] text-slate-500">
              Output on your sample rows (real rows plus deliberately awkward ones:
              an empty row, a truncated row, a number stored as text, a duplicate key)
            </span>
            <pre className="overflow-x-auto rounded-md border border-slate-700 bg-slate-950/70 p-2 text-[10px] font-mono text-emerald-300">
              {summarise(phase.result.output)}
            </pre>
          </div>

          {!editingCode && (
            <button
              type="button"
              disabled={busy !== null}
              onClick={() =>
                act("Activate", () => activateSheetBindingCode(sourceId, name))
              }
              className="flex items-center gap-1 px-2.5 py-1.5 rounded-md bg-emerald-900/60 hover:bg-emerald-900 border border-emerald-700 text-[11px] text-emerald-100 disabled:opacity-50"
            >
              {busy === "Activate" ? (
                <Loader2 className="w-3 h-3 animate-spin" />
              ) : (
                <Check className="w-3 h-3" />
              )}
              I have read the code — activate it
            </button>
          )}
        </div>
      )}

      {/* ── An existing tier-2 binding: state, and the actions on it. ── */}
      {generated && phase.kind !== "review" && status && (
        <div className="space-y-2">
          <p className="text-[10px] text-slate-400">
            Generated from “{status.instruction}” by{" "}
            <code className="text-slate-300">{status.model_id}</code>. Script{" "}
            <code className="text-slate-300">{status.script_id}</code>.
          </p>

          {status.stale && (
            <div className="flex items-start gap-1.5 rounded-md border border-red-900 bg-red-950/30 px-2 py-1.5">
              <ShieldAlert className="w-3.5 h-3.5 text-red-400 shrink-0 mt-0.5" />
              <div>
                <p className="text-[11px] text-red-200">
                  Stale, and not running: {status.stale_reason}
                </p>
                {binding.operation === "write" && (
                  <p className="text-[10px] text-red-300/80">
                    It is a write, so it needs re-confirmation before it can run
                    again — re-test it, read the result, then activate it.
                  </p>
                )}
              </div>
            </div>
          )}

          {!status.stale && !status.activated && (
            <p className="text-[11px] text-amber-300 bg-amber-950/20 border border-amber-900 rounded-md px-2 py-1">
              Compiled but switched off. Review the code and activate it.
            </p>
          )}

          <div className="flex flex-wrap gap-1.5">
            <button
              type="button"
              disabled={busy !== null}
              onClick={() =>
                act("Re-test", () => retestSheetBindingCode(sourceId, name))
              }
              className="flex items-center gap-1 px-2.5 py-1.5 rounded-md bg-slate-800 hover:bg-slate-700 border border-slate-700 text-[11px] text-sky-400 disabled:opacity-50"
            >
              {busy === "Re-test" ? (
                <Loader2 className="w-3 h-3 animate-spin" />
              ) : (
                <RefreshCw className="w-3 h-3" />
              )}
              Re-test
            </button>

            {/* Regeneration is refused once a person has edited the code, and
                the button says so rather than failing when pressed. */}
            <button
              type="button"
              disabled={busy !== null || status.edited_by_human || writeBlocked}
              title={
                status.edited_by_human
                  ? "This code was edited by hand, so it is no longer regenerated — your fix stays."
                  : undefined
              }
              onClick={() => compile({ instruction: status.instruction ?? "", force: true })}
              className="flex items-center gap-1 px-2.5 py-1.5 rounded-md bg-slate-800 hover:bg-slate-700 border border-slate-700 text-[11px] text-violet-300 disabled:opacity-50"
            >
              {busy === "compile" ? (
                <Loader2 className="w-3 h-3 animate-spin" />
              ) : (
                <Code2 className="w-3 h-3" />
              )}
              Recompile
            </button>

            {status.activated && (
              <button
                type="button"
                disabled={busy !== null}
                onClick={() =>
                  act("Mark stale", () =>
                    markSheetBindingStale(sourceId, name, "switched off from the editor"),
                  )
                }
                className="px-2.5 py-1.5 rounded-md bg-slate-800 hover:bg-slate-700 border border-slate-700 text-[11px] text-red-400 disabled:opacity-50"
              >
                Switch off
              </button>
            )}
          </div>

          {status.edited_by_human && (
            <p className="text-[10px] text-sky-400">
              A person edited this code, so it will not be regenerated.
            </p>
          )}
        </div>
      )}

      {phase.kind === "error" && (
        <div className="space-y-1 rounded-md border border-red-900 bg-red-950/30 px-2 py-1.5">
          <p className="text-[11px] text-red-300 whitespace-pre-wrap">{phase.message}</p>
          <p className="text-[10px] text-slate-400">
            If generation cannot satisfy this, the reliable way forward is a
            declarative read binding plus a separate workflow step that does the
            computing — no generated code, nothing to re-verify.
          </p>
        </div>
      )}
    </div>
  );
}
